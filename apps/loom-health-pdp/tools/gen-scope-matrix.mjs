// Generates tests/scope_matrix_test.rego from the mapping tables:
//   - the W1-4 role-scope map (single source; apps/loom-health-cp/src/auth/role-scope-map.v1.json)
//   - policies/lhds/interactions/data.json
// Expectations are computed here, in JS, from those tables alone - never by
// calling the Rego under test. Token verification is mocked in this file (the
// seam: token_valid, claims, now); the verification path is covered by the signed
// fixtures in tests/authz_test.rego. Usage:
//   node tools/gen-scope-matrix.mjs [--check] [--root <pdp dir>] [--rolemap <path>]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const argv = process.argv.slice(2);
const opt = (name, dflt) => { const i = argv.indexOf(name); return i >= 0 ? resolve(argv[i + 1]) : dflt; };
const root = opt('--root', join(dirname(fileURLToPath(import.meta.url)), '..'));
const rolemap = JSON.parse(readFileSync(opt('--rolemap', join(root, '../loom-health-cp/src/auth/role-scope-map.v1.json')), 'utf8'));
const ix = JSON.parse(readFileSync(join(root, 'policies/lhds/interactions/data.json'), 'utf8'));
const out = join(root, 'tests/scope_matrix_test.rego');

const LETTERS = ['c', 'r', 'u', 's', 'd'];
const name = (...p) => p.join('_').replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '');
const J = JSON.stringify;
const FHIR_BASE = 'https://visn-01.health.example.test/fhir';
const DICOM_BASE = 'https://visn-01.health.example.test/dicomweb';

const lines = [
  '# GENERATED by tools/gen-scope-matrix.mjs from the W1-4 role-scope map and',
  '# policies/lhds/interactions/data.json. DO NOT EDIT. Each test fails if the Rego',
  '# permits/denies differently from the tables. Verification is mocked here; see',
  '# authz_test.rego for the signed-token path.',
  'package lhds.matrix_test',
  '',
  'import rego.v1',
  '',
  'import data.lhds.authz',
  '',
  'cfg := {"issuer": "https://health-cp.example.test", "jwks": "{}"}',
  '',
  `stamp := {"tenants": {"visn-01": {"bases": [${J(FHIR_BASE)}, ${J(DICOM_BASE)}]}}}`,
  '',
  'claims_for(over) := object.union({',
  '\t"iss": "https://health-cp.example.test", "aud": "' + FHIR_BASE + '", "jti": "j", "lhds_ver": "lhds-at/1",',
  '\t"tenant": "visn-01", "sub": "s", "sub_type": "user", "idp_tid": "t", "client_id": "c", "scope": "",',
  '\t"patient": "p1", "lhds_roles": [], "lhds_map_ver": "lhds-scope-map/1", "pou": ["TREAT"],',
  '\t"iat": 1899999990, "exp": 1900000290,',
  '}, over)',
  '',
  'dec(over, request) := d if {',
  '\td := authz.decision with input as {"access_token": "mock", "request": request}',
  '\t\twith data.lhds.authz.token_valid as true',
  '\t\twith data.lhds.authz.claims as claims_for(over)',
  '\t\twith data.lhds.authz.now as 1900000000',
  '\t\twith data.lhds.config as cfg',
  '\t\twith data.lhds.stamp as stamp',
  '}',
  '',
];

const fhirReq = (interaction, type, extra = {}) => ({
  service: 'fhir', interaction, tenant: 'visn-01', base: FHIR_BASE, resource_type: type, ...extra,
});
const emit = (n, over, request, allow, reason) => {
  lines.push(
    `test_${n} if {`,
    `\td := dec(${J({ ...over, aud: request.base })},${J(request)})`,
    `\td.allow == ${allow}`,
    `\td.reason == ${J(reason)}`,
    '}',
    '',
  );
};
const seen = new Set();
const once = (n) => { if (seen.has(n)) return false; seen.add(n); return true; };

// 1) Scope letter x every FHIR interaction, per compartment/sub_type pairing.
const pairs = [['system', 'system'], ['user', 'user'], ['patient', 'user']];
for (const [ctx, subType] of pairs) {
  for (const letter of LETTERS) {
    for (const [interaction, need] of Object.entries(ix.fhir)) {
      const extra = ctx === 'patient' ? { patient_compartment: ['p1'] } : {};
      const n = name('letter', ctx, letter, interaction);
      const allow = need === letter;
      emit(n, { sub_type: subType, scope: `${ctx}/Observation.${letter}` }, fhirReq(interaction, 'Observation', extra), allow, allow ? 'permit' : 'scope-denied');
    }
  }
}
// 1b) Compartment must fit the token's sub_type, both directions, for every scope-context.
for (const [ctx, subType] of [['system', 'user'], ['user', 'system'], ['patient', 'system']]) {
  emit(name('subtype_mismatch', ctx, subType), { sub_type: subType, scope: `${ctx}/Observation.cruds` }, fhirReq('read', 'Observation', { patient_compartment: ['p1'] }), false, 'scope-denied');
}

// 2) Every ceiling scope string in the role map, presented under the sub_type its
//    grant type implies, against every FHIR interaction on a type it covers.
const GRANT_SUBTYPE = { authorization_code: 'user', client_credentials: 'system' };
for (const role of rolemap.roles) {
  for (const [grant, scopes] of Object.entries(role.ceiling)) {
    for (const scope of scopes) {
      const m = /^(patient|user|system)\/([^.]+)\.([cruds]+)$/.exec(scope);
      if (!m) throw new Error(`unparseable ceiling scope in role map: ${scope}`);
      const type = m[2] === '*' ? 'Observation' : m[2];
      for (const [interaction, need] of Object.entries(ix.fhir)) {
        const n = name('ceiling', role.id, grant, scope, interaction);
        if (!once(n)) continue;
        const extra = m[1] === 'patient' ? { patient_compartment: ['p1'] } : {};
        const allow = m[3].includes(need);
        emit(n, { sub_type: GRANT_SUBTYPE[grant], scope }, fhirReq(interaction, type, extra), allow, allow ? 'permit' : 'scope-denied');
      }
    }
  }
}

// 3) Role-gated operations. Every operation named in the map x every role in the map:
//    permit iff the role lists it. FHIR-service ops also need a data scope (held here).
const allOps = [...new Set(rolemap.roles.flatMap((r) => r.operations))];
const dicomOps = new Set(Object.values(ix.dicom));
for (const role of rolemap.roles) {
  for (const op of allOps) {
    const allow = role.operations.includes(op);
    const over = { sub_type: 'system', scope: 'system/*.rs', lhds_roles: [role.id] };
    if (dicomOps.has(op)) {
      for (const [interaction, mapped] of Object.entries(ix.dicom)) {
        if (mapped !== op) continue;
        emit(name('dicomop', role.id, interaction), over, { service: 'dicom', interaction, tenant: 'visn-01', base: DICOM_BASE }, allow, allow ? 'permit' : 'role-denied');
      }
    } else {
      emit(name('fhirop', role.id, op), over, fhirReq(ix.fhir_operation, 'Patient', { op }), allow, allow ? 'permit' : 'role-denied');
    }
  }
}
const text = lines.join('\n');
if (argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('scope_matrix_test.rego is stale; run tools/gen-scope-matrix.mjs'); process.exit(1); }
  console.log('scope_matrix_test.rego up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${(text.match(/^test_/gm) || []).length} tests`);
}
