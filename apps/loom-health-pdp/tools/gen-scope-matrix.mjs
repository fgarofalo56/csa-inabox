// Generates tests/scope_matrix_test.rego from the mapping table
// (policies/lhds/mapping/data.json). Expectations are computed here, in JS, from
// the table alone - not by calling the Rego under test.
// Usage: node tools/gen-scope-matrix.mjs [--check] [--root <dir>]
// --check fails if the committed file is stale. --root lets a sandbox copy be generated.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const argv = process.argv.slice(2);
const ri = argv.indexOf('--root');
const root = ri >= 0 ? resolve(argv[ri + 1]) : join(dirname(fileURLToPath(import.meta.url)), '..');
const table = JSON.parse(readFileSync(join(root, 'policies/lhds/mapping/data.json'), 'utf8'));
const out = join(root, 'tests/scope_matrix_test.rego');
const LETTERS = ['c', 'r', 'u', 's', 'd'];
const rtype = (svc) => (svc === 'fhir' ? 'Observation' : 'dicom');
const id = (...p) => p.join('_').replace(/[^A-Za-z0-9_]/g, '_');

const lines = [
  '# GENERATED by tools/gen-scope-matrix.mjs from policies/lhds/mapping/data.json. DO NOT EDIT.',
  '# Every test fails if the Rego grants/denies differently from the table.',
  'package lhds.authz_test',
  '',
  'import rego.v1',
  '',
  'import data.lhds.authz',
  '',
  'req(svc, ix, rt) := {"service": svc, "interaction": ix, "tenant": "t1", "resource_type": rt}',
  '',
];
const emit = (name, token, svc, ix, allow) => {
  lines.push(
    `test_${name} if {`,
    `\td := authz.decision with input as {"token": ${JSON.stringify(token)}, "request": req("${svc}", "${ix}", "${rtype(svc)}")}`,
    `\td.allow == ${allow}`,
    `\td.reason == "${allow ? 'permit' : 'scope-denied'}"`,
    '}',
    '',
  );
};

// 1) Single-letter scope x every interaction: permit iff the letter matches.
for (const [svc, ixs] of Object.entries(table.interactions)) {
  for (const ctx of ['system', 'user']) {
    for (const letter of LETTERS) {
      const scope = `${ctx}/${rtype(svc)}.${letter}`;
      for (const [ix, need] of Object.entries(ixs)) {
        emit(id('scope', svc, ctx, letter, ix), { sub: 'u1', tenant: 't1', scopes: [scope] }, svc, ix, need === letter);
      }
    }
  }
}
// 2) Every role x every interaction: permit iff the role bundle has the needed letter
//    for a scope whose resource matches (wildcard only for fhir).
for (const [role, scopes] of Object.entries(table.roles)) {
  for (const [svc, ixs] of Object.entries(table.interactions)) {
    for (const [ix, need] of Object.entries(ixs)) {
      const allow = scopes.some((s) => {
        const m = /^system\/([^.]+)\.([cruds]+)$/.exec(s);
        if (!m) return false;
        const resOk = m[1] === rtype(svc) || (m[1] === '*' && svc === 'fhir');
        return resOk && m[2].includes(need);
      });
      emit(id('role', role, svc, ix), { sub: 'u1', tenant: 't1', roles: [role] }, svc, ix, allow);
    }
  }
}
const text = lines.join('\n');
if (argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('scope_matrix_test.rego is stale; run tools/gen-scope-matrix.mjs'); process.exit(1); }
  console.log('scope_matrix_test.rego up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${(text.match(/^test_/gm) || []).length} tests`);
}
